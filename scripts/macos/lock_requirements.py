"""Write scripts/macos/requirements-arm64.lock: every wheel the Mac app installs, with its SHA256.

build-app.sh installs the app's Python packages with ``pip install --require-hashes`` from that
file, so a wheel that changes on PyPI (or in transit) fails the build instead of shipping. The
versions come from backend/constraints.txt; this script only resolves them for the app's
platform and records each chosen wheel's hash.

Run it on an Apple Silicon Mac with the app's pinned Python (the one build-app.sh unpacks), after
changing backend/constraints.txt or the backend's dependencies:

    build/BibleLive.app/Contents/Resources/python/bin/python3 scripts/macos/lock_requirements.py

It downloads nothing but the package index metadata (``pip install --dry-run``).
backend/tests/test_macos_lock.py checks that the lock and constraints.txt agree.
"""

import json
import platform
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
LOCK = REPO / "scripts" / "macos" / "requirements-arm64.lock"
EXTRAS = ("audio", "gguf", "launcher")  # what build-app.sh installs
# Published only as source. Pure Python (pywebview's proxy_tools): build-app.sh builds it with the
# locked setuptools and no build isolation, so its build backend is hash-checked too.
SOURCE_ONLY = ("proxy-tools",)


def requirements() -> list[str]:
    with open(REPO / "backend" / "pyproject.toml", "rb") as fh:
        project = tomllib.load(fh)["project"]
    reqs = list(project["dependencies"])
    for extra in EXTRAS:
        reqs += project["optional-dependencies"][extra]
    return reqs


def main() -> int:
    if sys.platform != "darwin" or platform.machine() != "arm64":
        print("Run this on an Apple Silicon Mac, with the app's Python.", file=sys.stderr)
        return 1
    if sys.version_info[:2] != (3, 13):
        print(f"The app runs Python 3.13, not {sys.version.split()[0]}.", file=sys.stderr)
        return 1
    with tempfile.TemporaryDirectory() as tmp:
        req = Path(tmp) / "requirements.txt"
        req.write_text("\n".join(requirements()) + "\n", encoding="utf-8")
        report = Path(tmp) / "report.json"
        subprocess.run(
            [
                sys.executable,
                "-m",
                "pip",
                "install",
                "--dry-run",
                "--ignore-installed",
                "--quiet",
                "--disable-pip-version-check",
                "--only-binary=:all:",
                *(f"--no-binary={name}" for name in SOURCE_ONLY),
                "--report",
                str(report),
                "-r",
                str(req),
                "-c",
                str(REPO / "backend" / "constraints.txt"),
            ],
            check=True,
        )
        installs = json.loads(report.read_text(encoding="utf-8"))["install"]
    lines = []
    for item in sorted(installs, key=lambda i: i["metadata"]["name"].lower()):
        name = item["metadata"]["name"].lower()
        version = item["metadata"]["version"]
        sha256 = item["download_info"]["archive_info"]["hashes"]["sha256"]
        wheel = item["download_info"]["url"].rsplit("/", 1)[-1]
        lines.append(f"# {wheel}\n{name}=={version} \\\n    --hash=sha256:{sha256}")
    header = (
        "# Generated by scripts/macos/lock_requirements.py on macOS arm64, Python 3.13: do not "
        "edit.\n# The wheels BibleLive.app installs (backend + audio,gguf,launcher extras), versions\n"
        "# from backend/constraints.txt. build-app.sh installs them with pip --require-hashes.\n"
        f"# Source only (pure Python, built with the locked setuptools): {', '.join(SOURCE_ONLY)}.\n"
    )
    LOCK.write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {LOCK} ({len(lines)} packages)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
